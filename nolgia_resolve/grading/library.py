"""Install the NOLGIA grading files into Resolve's LUT folder, as they are needed.

    <LUT folder>/NOLGIA Grade/
        CST IN/<camera>.dctl              camera log to DWG/DI (and Rec.709)
        CST OUT/DWG to Rec.709 (NOLGIA display).dctl
        Corrections/Skin.dctl
        Looks/<family>/<look>.cube        the look at full strength (33 point, DWG/DI in and out)
        Looks/<family>/<look> 60%.dctl    the look at a strength: the cube through DEFINE_LUT, mixed
        Looks ACEScct/...                 the same for ACES projects

Everything is generated by this plugin's code, so the download carries no LUT
files and the library is the code. A file is rewritten only when its text
changed.
"""

import os

from . import colour as C
from . import dctl
from . import looks as L

SUBFOLDER = "NOLGIA Grade"
STRENGTH_STEPS = (10, 20, 30, 40, 50, 60, 70, 80, 90)

CAMERA_FILES = {cam: "CST IN/%s.dctl" % C.CAMERAS[cam][0].replace("/", "-") for cam in C.CAMERAS}
CAMERA_FILES["rec709"] = "CST IN/Rec.709 (NOLGIA display).dctl"
CST_OUT_FILE = "CST OUT/DWG to Rec.709 (NOLGIA display).dctl"
SKIN_FILE = "Corrections/Skin.dctl"


def _write_if_changed(path, text):
    try:
        with open(path, "r", encoding="utf-8") as handle:
            if handle.read() == text:
                return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".part"
    with open(tmp, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    os.replace(tmp, path)
    return True


def rel(path):
    """A path under the LUT folder as Resolve lists it."""
    return (SUBFOLDER + "/" + path).replace("\\", "/")


def install_base(lut_root):
    """The transform and correction DCTLs. Returns how many files changed."""
    changed = 0
    for name, text in dctl.all_files().items():
        changed += _write_if_changed(os.path.join(lut_root, SUBFOLDER, name), text)
    return changed


def strength_dctl(look, cube_name, strength, space):
    pct = int(round(strength * 100))
    return (dctl.HEADER.format(name="%s %d%%" % (look.name, pct),
                               what="%s at %d%%: the look's LUT (%s) mixed with the picture under it. Pick another "
                                    "strength from the same folder, or set Strength in the DCTL plugin." % (
                                        look.name, pct, L.SPACES[space][0]))
            + "DEFINE_LUT(look, %s)\n" % cube_name
            + "DEFINE_UI_PARAMS(strength, Strength, DCTLUI_SLIDER_FLOAT, %.2f, 0.0, 1.0, 0.01)\n\n" % strength
            + """__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B)
{
    float3 l = APPLY_LUT(p_R, p_G, p_B, look);
    return make_float3(p_R + (l.x - p_R) * strength, p_G + (l.y - p_G) * strength, p_B + (l.z - p_B) * strength);
}
""")


def install_look(lut_root, look, strength=1.0, space="dwg", size=33):
    """The look's cube, and its strength DCTLs; returns the path the LOOK node takes."""
    cube_rel = L.file_name(look, space)
    folder = os.path.dirname(os.path.join(lut_root, SUBFOLDER, cube_rel))
    cube_path = os.path.join(lut_root, SUBFOLDER, cube_rel)
    _write_if_changed(cube_path, L.cube_text(look, size, space))
    cube_name = os.path.basename(cube_path)
    pct = int(round(strength * 100))
    for step in sorted(set(STRENGTH_STEPS) | ({pct} if 0 < pct < 100 else set())):
        name = "%s %d%%.dctl" % (look.name, step)
        _write_if_changed(os.path.join(folder, name), strength_dctl(look, cube_name, step / 100.0, space))
    if pct >= 100:
        return rel(cube_rel)
    return rel(os.path.join(os.path.dirname(cube_rel), "%s %d%%.dctl" % (look.name, pct)))


def install_all_looks(lut_root, space="dwg"):
    """Every look at full strength and the 10% steps, so they are all in Resolve's LUT browser."""
    return [install_look(lut_root, look, 1.0, space) for look in L.LOOKS]
